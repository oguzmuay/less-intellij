package dev.lessai.status

import dev.lessai.session.CommandBuilder
import dev.lessai.session.LaunchContext
import dev.lessai.session.SessionStatus
import java.nio.file.Files

/** Authoritative Claude status: reads the status file written by the session's Claude Code hooks. */
class ClaudeHookStatusSource(sessionId: String) : StatusSource {

    private val watcher = StatusFileWatcher(StatusFiles.statusFile(sessionId))

    /** Starts watching the hook status file. */
    override fun start(sink: (SessionStatus) -> Unit) = watcher.start(sink)

    /** Stops watching. */
    override fun dispose() = watcher.dispose()

    companion object {

        /**
         * Writes the hook script and `--settings` JSON for the session and returns the CLI args that load them.
         * Example: "abc" -> extraArgs ["--settings", "'<system>/less-ai/status/abc.settings.json'"]
         */
        fun prepareLaunch(sessionId: String): LaunchContext {
            val statusFile = StatusFiles.statusFile(sessionId)
            Files.deleteIfExists(statusFile)
            val script = StatusFiles.hookScript(sessionId)
            Files.writeString(script, hookScript(statusFile.toString()))
            val settings = StatusFiles.claudeSettingsFile(sessionId)
            Files.writeString(settings, settingsJson(script.toString()))
            return LaunchContext(extraArgs = listOf("--settings", CommandBuilder.shellQuote(settings.toString())))
        }

        /**
         * POSIX sh hook body; `$1` is a status word, or `notify` to classify the Notification payload on stdin.
         * Example: `sh hook.sh working` -> status file contains "working"
         */
        private fun hookScript(statusFile: String): String = """
            |#!/bin/sh
            |# Generated by the LESS AI IntelliJ plugin; writes the Claude session status.
            |f=${CommandBuilder.shellQuote(statusFile)}
            |input=${'$'}(cat 2>/dev/null)
            |case "${'$'}1" in
            |  notify)
            |    case "${'$'}input" in
            |      *permission_prompt*|*elicitation*|*"needs your permission"*|*"your approval"*|*"approve"*) s=approval ;;
            |      *) s=idle ;;
            |    esac ;;
            |  *) s="${'$'}1" ;;
            |esac
            |printf '%s\n' "${'$'}s" > "${'$'}f.tmp" && mv -f "${'$'}f.tmp" "${'$'}f"
            |exit 0
            |""".trimMargin()

        /**
         * Claude Code settings JSON registering the status hooks.
         * Example: UserPromptSubmit -> `sh '<script>' working`
         */
        private fun settingsJson(script: String): String {
            val base = "sh " + CommandBuilder.shellQuote(script)
            /** One hook-event value: a single command hook running the script with [arg]. */
            fun entry(arg: String, matcher: String? = null): String {
                val m = matcher?.let { "\"matcher\":${CommandBuilder.jsonString(it)}," } ?: ""
                val cmd = CommandBuilder.jsonString("$base $arg")
                return "[{$m\"hooks\":[{\"type\":\"command\",\"command\":$cmd}]}]"
            }
            val hooks = listOf(
                "SessionStart" to entry("idle"),
                "UserPromptSubmit" to entry("working"),
                "PostToolUse" to entry("working", "*"),
                "Stop" to entry("idle"),
                "Notification" to entry("notify")
            )
            return hooks.joinToString(",", prefix = "{\"hooks\":{", postfix = "}}\n") { (event, value) ->
                "\"$event\":$value"
            }
        }
    }
}
